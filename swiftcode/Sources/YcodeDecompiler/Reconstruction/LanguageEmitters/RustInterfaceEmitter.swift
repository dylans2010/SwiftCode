import Foundation

public struct RustInterfaceEmitter: InterfaceEmitter {
    public init() {}

    public var language: SourceLanguage { .rust }

    public func emit(libraryName: String, records: [ReconstructionRecord]) -> InterfaceEmission {
        var lines: [String] = []
        lines.append("// Rust interface for \(libraryName) (generated by SwiftCode; each function forwards to its reconstructed C implementation).")
        lines.append("extern \"C\" {")
        var shims: [InterfaceShim] = []
        var omitted: [InterfaceOmission] = []
        var pending: [(record: ReconstructionRecord, externName: String,
                       returnType: String, params: [(name: String, type: String)])] = []
        for record in records.sorted(by: { $0.functionAddress.value < $1.functionAddress.value }) {
            if record.quality == .unresolved || record.quality == .unsupported {
                let reason = record.quality == .unresolved
                    ? "no implementation was recovered"
                    : "reconstruction is not supported for this function"
                omitted.append(InterfaceOmission(functionAddress: record.functionAddress.value,
                                                 recoveredName: record.recoveredName,
                                                 quality: record.quality, reason: reason))
                continue
            }
            guard let parsed = InterfaceSignatureParsing.parse(record: record) else {
                omitted.append(InterfaceOmission(functionAddress: record.functionAddress.value,
                                                 recoveredName: record.recoveredName,
                                                 quality: record.quality,
                                                 reason: "its C signature could not be parsed into a typed interface"))
                continue
            }
            guard let returnType = Self.rustType(for: parsed.returnType) else {
                omitted.append(InterfaceOmission(functionAddress: record.functionAddress.value,
                                                 recoveredName: record.recoveredName,
                                                 quality: record.quality,
                                                 reason: "its return type '\(parsed.returnType)' has no Rust equivalent"))
                continue
            }
            var rustParams: [(name: String, type: String)] = []
            var unmappableType: String?
            var unmappableName: String?
            for param in parsed.parameters {
                guard let paramType = Self.rustType(for: param.type) else {
                    unmappableType = param.type
                    break
                }
                guard let paramName = Self.rustIdentifier(param.name) else {
                    unmappableName = param.name
                    break
                }
                rustParams.append((name: paramName, type: paramType))
            }
            if let unmappableType {
                omitted.append(InterfaceOmission(functionAddress: record.functionAddress.value,
                                                 recoveredName: record.recoveredName,
                                                 quality: record.quality,
                                                 reason: "its parameter type '\(unmappableType)' has no Rust equivalent"))
                continue
            }
            if let unmappableName {
                omitted.append(InterfaceOmission(functionAddress: record.functionAddress.value,
                                                 recoveredName: record.recoveredName,
                                                 quality: record.quality,
                                                 reason: "its parameter name '\(unmappableName)' cannot be expressed as a Rust identifier"))
                continue
            }
            guard let externName = Self.rustIdentifier(record.recoveredName) else {
                omitted.append(InterfaceOmission(functionAddress: record.functionAddress.value,
                                                 recoveredName: record.recoveredName,
                                                 quality: record.quality,
                                                 reason: "its name cannot be expressed as a Rust identifier"))
                continue
            }
            let paramList = rustParams.map { "\($0.name): \($0.type)" }.joined(separator: ", ")
            if returnType == "()" {
                lines.append("    fn \(externName)(\(paramList));")
            } else {
                lines.append("    fn \(externName)(\(paramList)) -> \(returnType);")
            }
            pending.append((record: record, externName: externName, returnType: returnType, params: rustParams))
        }
        lines.append("}")
        lines.append("")
        for entry in pending {
            let record = entry.record
            let shimSymbol = record.recoveredName + "_rs"
            let paramList = entry.params.map { "\($0.name): \($0.type)" }.joined(separator: ", ")
            let callArgs = entry.params.map(\.name).joined(separator: ", ")
            let externName = entry.externName
            let shimLine = lines.count + 1
            lines.append("#[no_mangle]")
            if entry.returnType == "()" {
                lines.append("pub extern \"C\" fn \(shimSymbol)(\(paramList)) {")
            } else {
                lines.append("pub extern \"C\" fn \(shimSymbol)(\(paramList)) -> \(entry.returnType) {")
            }
            lines.append("    unsafe { \(externName)(\(callArgs)) }")
            lines.append("}")
            lines.append("")
            shims.append(InterfaceShim(functionAddress: record.functionAddress.value, line: shimLine,
                                       recoveredName: record.recoveredName, shimSymbol: shimSymbol,
                                       quality: record.quality))
        }
        if !omitted.isEmpty {
            lines.append("// Not emitted (no shim was generated):")
            for omission in omitted {
                lines.append("// - \(omission.recoveredName) (\(omission.quality.displayName)): \(omission.reason).")
            }
        }
        let file = GeneratedSourceFile(relativePath: "Sources/\(libraryName).rs",
                                       contents: lines.joined(separator: "\n") + "\n",
                                       language: .rust,
                                       quality: InterfaceEmitterRegistry.fileQuality(for: shims))
        return InterfaceEmission(file: file, shims: shims, omitted: omitted)
    }

    static func rustType(for cType: String) -> String? {
        let (base, depth, isConst) = InterfaceSignatureParsing.splitCType(cType)
        if depth > 0 {
            let inner: String
            if base == "void" {
                inner = "core::ffi::c_void"
            } else if let scalar = rustScalarType(base) {
                inner = scalar
            } else {
                inner = "core::ffi::c_void"
            }
            var result = inner
            for _ in 0..<depth {
                result = isConst ? "*const \(result)" : "*mut \(result)"
            }
            return result
        }
        return rustScalarType(base)
    }

    static func rustScalarType(_ base: String) -> String? {
        switch base {
        case "void", "code": return "()"
        case "bool", "_Bool": return "bool"
        case "char", "signed char": return "core::ffi::c_char"
        case "unsigned char": return "core::ffi::c_uchar"
        case "short": return "core::ffi::c_short"
        case "unsigned short": return "core::ffi::c_ushort"
        case "int": return "core::ffi::c_int"
        case "unsigned int", "unsigned": return "core::ffi::c_uint"
        case "long": return "core::ffi::c_long"
        case "unsigned long": return "core::ffi::c_ulong"
        case "long long": return "core::ffi::c_longlong"
        case "unsigned long long": return "core::ffi::c_ulonglong"
        case "float": return "core::ffi::c_float"
        case "double": return "core::ffi::c_double"
        case "int8_t": return "i8"
        case "uint8_t": return "u8"
        case "int16_t": return "i16"
        case "uint16_t": return "u16"
        case "int32_t": return "i32"
        case "uint32_t": return "u32"
        case "int64_t": return "i64"
        case "uint64_t": return "u64"
        case "intptr_t": return "isize"
        case "uintptr_t": return "usize"
        case "size_t": return "usize"
        case "ssize_t": return "isize"
        case "undefined", "undefined1": return "u8"
        case "undefined2": return "u16"
        case "undefined4": return "u32"
        case "undefined8": return "u64"
        case "byte": return "u8"
        case "word": return "u16"
        case "dword": return "u32"
        case "qword": return "u64"
        case "ulong": return "u64"
        case "uint": return "u32"
        case "ushort": return "u16"
        case "uchar": return "u8"
        default: return nil
        }
    }

    static func rustIdentifier(_ name: String) -> String? {
        if name == "self" || name == "Self" || name == "super" || name == "crate" {
            return nil
        }
        if rustKeywords.contains(name) {
            return "r#\(name)"
        }
        return name
    }

    static let rustKeywords: Set<String> = [
        "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false",
        "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut",
        "pub", "ref", "return", "self", "Self", "static", "struct", "super", "trait",
        "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn",
        "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof",
        "unsized", "virtual", "yield", "try", "union",
    ]
}
