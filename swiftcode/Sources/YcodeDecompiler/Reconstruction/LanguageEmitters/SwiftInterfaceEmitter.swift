import Foundation

public struct SwiftInterfaceEmitter: InterfaceEmitter {
    public init() {}

    public var language: SourceLanguage { .swift }

    public func emit(libraryName: String, records: [ReconstructionRecord]) -> InterfaceEmission {
        var lines: [String] = []
        lines.append("// Swift interface for \(libraryName) (generated by SwiftCode; each function forwards to its reconstructed C implementation).")
        lines.append("#if canImport(Darwin)")
        lines.append("import Darwin")
        lines.append("#elseif canImport(Glibc)")
        lines.append("import Glibc")
        lines.append("#endif")
        lines.append("")
        var shims: [InterfaceShim] = []
        var omitted: [InterfaceOmission] = []
        for record in records.sorted(by: { $0.functionAddress.value < $1.functionAddress.value }) {
            if record.quality == .unresolved || record.quality == .unsupported {
                let reason = record.quality == .unresolved
                    ? "no implementation was recovered"
                    : "reconstruction is not supported for this function"
                omitted.append(InterfaceOmission(functionAddress: record.functionAddress.value,
                                                 recoveredName: record.recoveredName,
                                                 quality: record.quality, reason: reason))
                continue
            }
            guard let parsed = InterfaceSignatureParsing.parse(record: record) else {
                omitted.append(InterfaceOmission(functionAddress: record.functionAddress.value,
                                                 recoveredName: record.recoveredName,
                                                 quality: record.quality,
                                                 reason: "its C signature could not be parsed into a typed interface"))
                continue
            }
            guard let returnType = Self.swiftType(for: parsed.returnType) else {
                omitted.append(InterfaceOmission(functionAddress: record.functionAddress.value,
                                                 recoveredName: record.recoveredName,
                                                 quality: record.quality,
                                                 reason: "its return type '\(parsed.returnType)' has no Swift equivalent"))
                continue
            }
            var swiftParams: [(name: String, type: String)] = []
            var unmappableType: String?
            for param in parsed.parameters {
                guard let paramType = Self.swiftType(for: param.type) else {
                    unmappableType = param.type
                    break
                }
                swiftParams.append((name: Self.swiftIdentifier(param.name), type: paramType))
            }
            if let unmappableType {
                omitted.append(InterfaceOmission(functionAddress: record.functionAddress.value,
                                                 recoveredName: record.recoveredName,
                                                 quality: record.quality,
                                                 reason: "its parameter type '\(unmappableType)' has no Swift equivalent"))
                continue
            }
            let cName = record.recoveredName
            let shimSymbol = cName + "_swift"
            let helperName = "__sc_c_" + cName
            let paramList = swiftParams.map { "_ \($0.name): \($0.type)" }.joined(separator: ", ")
            let callArgs = swiftParams.map(\.name).joined(separator: ", ")
            lines.append("@_silgen_name(\"\(cName)\")")
            if returnType == "Void" {
                lines.append("func \(helperName)(\(paramList))")
            } else {
                lines.append("func \(helperName)(\(paramList)) -> \(returnType)")
            }
            lines.append("")
            let shimLine = lines.count + 1
            let swiftName = Self.swiftFunctionName(cName)
            lines.append("@_cdecl(\"\(shimSymbol)\")")
            if returnType == "Void" {
                lines.append("public func \(swiftName)(\(paramList)) {")
            } else {
                lines.append("public func \(swiftName)(\(paramList)) -> \(returnType) {")
            }
            lines.append("    \(helperName)(\(callArgs))")
            lines.append("}")
            lines.append("")
            shims.append(InterfaceShim(functionAddress: record.functionAddress.value, line: shimLine,
                                       recoveredName: cName, shimSymbol: shimSymbol,
                                       quality: record.quality))
        }
        if !omitted.isEmpty {
            lines.append("// Not emitted (no shim was generated):")
            for omission in omitted {
                lines.append("// - \(omission.recoveredName) (\(omission.quality.displayName)): \(omission.reason).")
            }
        }
        let file = GeneratedSourceFile(relativePath: "Sources/\(libraryName).swift",
                                       contents: lines.joined(separator: "\n") + "\n",
                                       language: .swift,
                                       quality: InterfaceEmitterRegistry.fileQuality(for: shims))
        return InterfaceEmission(file: file, shims: shims, omitted: omitted)
    }

    static func swiftType(for cType: String) -> String? {
        let (base, depth, isConst) = InterfaceSignatureParsing.splitCType(cType)
        if depth > 0 {
            if base == "void" {
                return isConst ? "UnsafeRawPointer" : "UnsafeMutableRawPointer"
            }
            if depth == 1, let scalar = swiftScalarType(base), scalar != "Void" {
                return isConst ? "UnsafePointer<\(scalar)>" : "UnsafeMutablePointer<\(scalar)>"
            }
            return isConst ? "UnsafeRawPointer" : "UnsafeMutableRawPointer"
        }
        return swiftScalarType(base)
    }

    static func swiftScalarType(_ base: String) -> String? {
        switch base {
        case "void", "code": return "Void"
        case "bool", "_Bool": return "Bool"
        case "char", "signed char": return "CChar"
        case "unsigned char": return "CUnsignedChar"
        case "short": return "CShort"
        case "unsigned short": return "CUnsignedShort"
        case "int": return "CInt"
        case "unsigned int", "unsigned": return "CUnsignedInt"
        case "long": return "CLong"
        case "unsigned long": return "CUnsignedLong"
        case "long long": return "CLongLong"
        case "unsigned long long": return "CUnsignedLongLong"
        case "float": return "CFloat"
        case "double": return "CDouble"
        case "int8_t": return "Int8"
        case "uint8_t": return "UInt8"
        case "int16_t": return "Int16"
        case "uint16_t": return "UInt16"
        case "int32_t": return "Int32"
        case "uint32_t": return "UInt32"
        case "int64_t": return "Int64"
        case "uint64_t": return "UInt64"
        case "intptr_t": return "Int"
        case "uintptr_t": return "UInt"
        case "size_t": return "UInt"
        case "ssize_t": return "Int"
        case "undefined", "undefined1": return "UInt8"
        case "undefined2": return "UInt16"
        case "undefined4": return "UInt32"
        case "undefined8": return "UInt64"
        case "byte": return "UInt8"
        case "word": return "UInt16"
        case "dword": return "UInt32"
        case "qword": return "UInt64"
        case "ulong": return "UInt64"
        case "uint": return "UInt32"
        case "ushort": return "UInt16"
        case "uchar": return "UInt8"
        default: return nil
        }
    }

    static func swiftIdentifier(_ name: String) -> String {
        swiftKeywords.contains(name) ? "`\(name)`" : name
    }

    static func swiftFunctionName(_ cName: String) -> String {
        if cName == "init" || cName == "deinit" || cName == "subscript" {
            return cName + "_swift"
        }
        return swiftIdentifier(cName)
    }

    static let swiftKeywords: Set<String> = [
        "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func",
        "import", "init", "inout", "internal", "let", "open", "operator", "private",
        "precedencegroup", "protocol", "Protocol", "public", "rethrows", "static", "struct",
        "subscript", "typealias", "var", "break", "case", "catch", "continue", "default",
        "defer", "do", "else", "fallthrough", "for", "guard", "if", "in", "repeat", "return",
        "switch", "where", "while", "as", "Any", "false", "is", "nil", "self", "Self",
        "super", "throw", "throws", "true", "try", "await",
    ]
}
