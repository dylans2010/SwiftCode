import Foundation



public enum AssemblyExporter {
    
    
    
    public static func export(instructions: [Instruction],
                              includeBytes: Bool = true,
                              includeHeader: Bool = true) -> String {
        let sorted = instructions.sorted { $0.address.value < $1.address.value }

        
        let byteTexts: [String] = sorted.map {
            $0.rawBytes.map { String(format: "%02x", $0) }.joined(separator: " ")
        }
        let byteColumnWidth = byteTexts.map(\.count).max() ?? 0

        var out = ""
        if includeHeader {
            out += "; Disassembly listing\n"
            out += "; Generated by SwiftCode Decompiler\n"
            out += "; Instructions: \(sorted.count)\n\n"
        }
        for (index, ins) in sorted.enumerated() {
            var line = ins.address.description
            line += "  "
            if includeBytes {
                let bytes = byteTexts[index]
                line += bytes
                line += String(repeating: " ", count: max(0, byteColumnWidth - bytes.count))
                line += "  "
            }
            line += ins.mnemonic
            if !ins.operandText.isEmpty { line += " \(ins.operandText)" }
            var suffixes: [String] = []
            if let label = ins.label { suffixes.append("label: \(label)") }
            if let comment = ins.comment { suffixes.append(comment) }
            if !suffixes.isEmpty { line += "  ; \(suffixes.joined(separator: "  "))" }
            out += line + "\n"
        }
        return out
    }

    
    public static func export(instructions: [Instruction],
                              function: DecompilerFunction,
                              includeBytes: Bool = true) -> String {
        let start = function.address.value
        let end = function.endAddress?.value
            ?? start + max(function.size, 1)
        let scoped = instructions.filter {
            $0.address.value >= start && $0.address.value < end
        }
        var header = ""
        if !scoped.isEmpty {
            header = "; Function \(function.displayName) @ \(function.address.description)\n\n"
        }
        return header + export(instructions: scoped, includeBytes: includeBytes,
                               includeHeader: false)
    }
}
