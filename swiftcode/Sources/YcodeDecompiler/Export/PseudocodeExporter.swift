import Foundation



public enum PseudocodeExporter {
    
    
    
    public static func export(results: [DecompilationResult],
                              functions: [DecompilerFunction] = []) -> String {
        let byAddress = Dictionary(uniqueKeysWithValues: functions.map { ($0.address.value, $0) })
        let sorted = results.sorted { $0.functionAddress.value < $1.functionAddress.value }

        var out = "// Decompiled pseudocode export\n"
        out += "// Generated by SwiftCode Decompiler\n"
        out += "// Functions: \(sorted.count)\n\n"

        for result in sorted {
            let fn = byAddress[result.functionAddress.value]
            out += "/* ================================================ */\n"
            out += "/* Function: \(result.functionName)\n"
            out += "/* Address:  \(result.functionAddress.description)"
            if let fn {
                out += "  Size: \(fn.size) bytes  Kind: \(fn.kind.rawValue)"
            }
            out += "\n/* Engine:   \(result.engineID)"
            if let version = result.engineVersion { out += " \(version)" }
            out += " */\n/* ================================================ */\n"

            if let signature = result.signature, !signature.isEmpty {
                out += signature + "\n"
            } else {
                let params = result.parameters.joined(separator: ", ")
                let ret = result.returnType ?? "void"
                out += "\(ret) \(result.functionName)(\(params))\n"
            }
            out += "{\n"
            for line in result.pseudocode.split(separator: "\n", omittingEmptySubsequences: false) {
                out += "    \(line)\n"
            }
            out += "}\n"

            for warning in result.warnings {
                out += "// warning [\(result.engineID)]: \(warning)\n"
            }
            out += "\n"
        }
        return out
    }

    
    public static func export(result: DecompilationResult,
                              function: DecompilerFunction? = nil) -> String {
        export(results: [result], functions: function.map { [$0] } ?? [])
    }
}
